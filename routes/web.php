// Stored files (payslip/MPR PDFs, NIC scans, receipts) are streamed through the
// app rather than served off a `public/storage` symlink: the symlink cannot be
// created on every host, and it would expose one company's files to another.
// Accepts a panel session or a Sanctum token so API `pdf_url`s work too.
// Bound by id, not the model's `slug` route key: the on-disk directory is
// `tenants/{id}`, and keying the URL the same way keeps the two from drifting.
Route::get(TenantStorage::URL_PREFIX.'/{company:id}/{path}', [TenantFileController::class, 'show'])
    ->where('path', '.*')
    ->middleware(['auth:web,sanctum', \App\Http\Middleware\RequireTokenAbility::class])
    ->name('tenant-file');

// The document `whatsapp:test` hands a provider to fetch, so the Twilio driver — which sends media
// by link rather than by upload — can be tested at all. Signed in the path and short-lived: there is
// no session here because the reader is Twilio, and the signature is the whole of the authorization.
// See App\Support\DeliveryTestLink.
Route::middleware(['web'])
    ->get('/delivery-test/{expires}/{signature}/{filename}', DeliveryTestMediaController::class)
    ->whereNumber('expires')
    ->where('signature', '[a-f0-9]{64}')
    ->where('filename', '[A-Za-z0-9._-]+')
    ->name('delivery-test.media');

