// The health checks' results, rendered by spatie/laravel-health's own page — the
// scheduled `health:check` writes them, this only reads (`?fresh` re-runs on demand).
// Super admins only, checked directly and NOT via a Gate: AppServiceProvider's
// Gate::before answers every non-`create` ability with true for a company
// Administrator, and this page shows every tenant's health at once. Same posture as
// HorizonServiceProvider::authorization(). Linked from the platform panel's
// Operations group.
Route::get('/ops/health', function (Illuminate\Http\Request $request) {
    abort_unless((bool) $request->user()?->isSuperAdmin(), 403);

    // Container-called: the controller asks for the result store and clock beside the request.
    return app()->call(Spatie\Health\Http\Controllers\HealthCheckResultsController::class.'@__invoke');
})->middleware(['web', 'auth'])->name('ops.health');

// Returning from impersonation. A plain route rather than a Livewire action so
// the way back works from any page in the panel, including one that fails to
// render — being stuck as somebody else is the failure mode to avoid.
Route::post('/impersonate/stop', function () {
    $impersonation = app(App\Support\Impersonation::class);

    // Read before the swap, because the session is regenerated by it.
    $returnUrl = $impersonation->returnUrlAndForget();

    $impersonator = $impersonation->stop();

    if (! $impersonator) {
        return redirect()->back();
    }

    \Filament\Notifications\Notification::make()
        ->success()
        ->title('Welcome back, '.$impersonator->name)
        ->send();

    // Back where it started: a platform admin returns to /platform, a company
    // Administrator to their own company. Falling back to the admin panel for a session
    // that predates this, or one begun outside a panel.
    return redirect($returnUrl ?? \Filament\Facades\Filament::getPanel('admin')->getUrl());
})->middleware(['web', 'auth'])->name('impersonate.stop');

// Per-user UI preferences — the server-side home the table context menu's off switch
// waited for (docs/table-context-menu-plan.md Phase 4). An allow-listed key, not a free
// key-value store: anything with a session can POST here, so the client only gets to set
// flags this application knows about — the posture DashboardLayout::KEYS takes.
Route::post('/user/preferences', function (Illuminate\Http\Request $request) {
    $data = $request->validate([
        'key' => ['required', 'string', 'in:tableContextMenuDisabled'],
        'value' => ['required', 'boolean'],
    ]);

    $user = $request->user();
    $user->preferences = array_merge((array) $user->preferences, [$data['key'] => $request->boolean('value')]);
    $user->save();

    return response()->noContent();
})->middleware(['web', 'auth'])->name('user.preferences');
